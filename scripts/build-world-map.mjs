// Generates src/apps/maps/worldPath.ts from Natural Earth 110m land (world-atlas).
// Run with `npm run build:map`. Only this script uses these dev dependencies; the app never imports them.
import { readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { geoEquirectangular, geoPath } from 'd3-geo'
import { feature } from 'topojson-client'

// Must match MAP_W and MAP_H in src/apps/maps/project.ts.
const MAP_W = 1000
const MAP_H = 500

const require = createRequire(import.meta.url)
const topo = JSON.parse(readFileSync(require.resolve('world-atlas/land-110m.json'), 'utf8'))
const land = feature(topo, topo.objects.land)

const projection = geoEquirectangular()
  .scale(MAP_W / (2 * Math.PI))
  .translate([MAP_W / 2, MAP_H / 2])
const raw = geoPath(projection)(land)

// One decimal keeps the path small and is far below a pixel at any window size.
const rounded = raw.replace(/-?\d+(\.\d+)?/g, (n) => String(Math.round(Number(n) * 10) / 10))
if (/\d[eE][-+]?\d/.test(rounded)) throw new Error('unexpected exponent notation in path data')
if (!rounded.startsWith('M')) throw new Error('path does not start with M')

const out = `// Generated by scripts/build-world-map.mjs from Natural Earth 110m land (world-atlas) — do not edit
export const WORLD_PATH = '${rounded}'
`
writeFileSync(new URL('../src/apps/maps/worldPath.ts', import.meta.url), out)
console.log(`wrote src/apps/maps/worldPath.ts (${(out.length / 1024).toFixed(1)} KB)`)
